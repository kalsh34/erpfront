const dictionaries: Record<Language, Record<DictKey, string>> = { en, am };

/** Values for `{placeholder}` tokens inside dictionary strings. */
export type TParams = Record<string, string | number>;

function interpolate(template: string, params?: TParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match
  );
}

/** Translate a key in the current UI language (English fallback). */
export function translate(lang: Language, key: DictKey, params?: TParams): string {
  const template = dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? key;
  return interpolate(template, params);
}

/** React hook: `const t = useT(); t('totalBadge', { count: 42 })`
 *
 * Returns a STABLE function (changes only when the language changes). Pages
 * put `t` in useCallback/useEffect dependency arrays — a fresh function per
 * render there caused infinite refetch loops. */
export function useT() {
  const language = useUIStore((s) => s.language);
  return useCallback((key: DictKey, params?: TParams) => translate(language, key, params), [language]);
}

/** React hook: the current UI language (for locale-aware formatting). */
export function useLang(): Language {
  return useUIStore((s) => s.language);
}

const monthNamesByLang: Record<Language, string[]> = {
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
  am: ['ጃንዋሪ', 'ፌብሩዋሪ', 'ማርች', 'ኤፕሪል', 'ሜይ', 'ጁን', 'ጁላይ', 'ኦገስት', 'ሴፕቴምበር', 'ኦክቶበር', 'ኖቬምበር', 'ዲሴምበር'],
};

export function getMonthNames(lang: Language): string[] {
  return monthNamesByLang[lang] ?? monthNamesByLang.en;
}

/** Locale-aware short date, e.g. `12 Mar 2026` / `12 ማርች 2026`. Gregorian always. */
export function formatDate(lang: Language, iso?: string): string {
  if (!iso) return '—';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '—';
  return `${String(d.getDate()).padStart(2, '0')} ${getMonthNames(lang)[d.getMonth()]} ${d.getFullYear()}`;
}

